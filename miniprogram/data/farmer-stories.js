function storiesForSeason(seasonId) {
  return (IDS[seasonId] || []).map(id => {
    const story = STORIES[id];
    if (!story) return null;
    const fruit = culture.findFruit(id);
    const illustration = id === 'autumn-persimmon'
      ? '/assets/illustrations/farmer-story-scene.jpg'
      : '/assets/illustrations/farmer-story-care.jpg';
    return { id, fruit: fruit ? fruit.name : id, name: story.name, place: story.place, text: story.text, illustration, editorialType: 'field-story' };
  }).filter(Boolean);
}
function storyForSeason(seasonId, date) {
  const list = storiesForSeason(seasonId); if (!list.length) return null;
  const now = date ? new Date(date) : new Date();
  const day = Number.isFinite(now.getTime()) ? Math.floor(Date.UTC(now.getFullYear(), now.getMonth(), now.getDate()) / 86400000) : 0;
  return list[day % list.length];
}
module.exports = { storiesForSeason, storyForSeason };
