let cachedLang = null;
// 语言存于当前账户分区（个人 / 演示）的 settings.language，与 lib/store.js 的分区键保持一致。
const MODE_KEY = 'guayouji.active-mode.v1';
const PERSONAL_KEY = 'guayouji.prototype.v1';
const DEMO_KEY = 'guayouji.demo.v1';
function getLang() {
  if (cachedLang) return cachedLang;
  let lang = 'zh';
  try {
    if (typeof wx !== 'undefined' && wx.getStorageSync) {
      const key = wx.getStorageSync(MODE_KEY) === 'demo' ? DEMO_KEY : PERSONAL_KEY;
      const state = wx.getStorageSync(key);
      if (state && state.settings && state.settings.language === 'en') lang = 'en';
    }
  } catch (error) { lang = 'zh'; }
  cachedLang = lang;
  return lang;
}
function invalidateLang() { cachedLang = null; }

// t('key') → 当前语言文案；t('key', {n:1}) 支持 {{n}} 占位。
function t(key, vars) {
  const entry = dict[key];
  const text = entry ? entry[getLang() === 'en' ? 1 : 0] : key;
  if (!vars) return text;
  return Object.keys(vars).reduce((acc, name) => acc.split('{{' + name + '}}').join(String(vars[name])), text);
}

// 页面标签集：传一组 key，返回 {key: 文案} 供 WXML 绑定。
Object.assign(dict, chatDict);

function labels(keys) {
  const out = {};
  keys.forEach(key => { out[key] = t(key); });
  return out;
}

// 导航栏标题按当前语言设置（json 里的静态标题作兜底）。
function applyNav(key) {
  if (typeof wx === 'undefined' || typeof wx.setNavigationBarTitle !== 'function') return;
  wx.setNavigationBarTitle({ title: t(key) });
}
module.exports = { t, labels, getLang, setLangProxy: null, invalidateLang, applyNav, dict };
